import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import * as THREE from 'three';
import {cameraScale} from '../lib/coordinates.ts';

const source=fs.readFileSync('lib/bubble-renderer.ts','utf8');
const prefix=source.slice(source.indexOf('  draw('),source.indexOf('    for(const slot'))+'}';
const code=ts.transpileModule(`class Subject{${prefix}}`,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const Subject=new Function('THREE','cameraScale',code+';return Subject;')(THREE,cameraScale);
let frame;
const video={readyState:2,videoWidth:1280,videoHeight:720,currentTime:0,requestVideoFrameCallback(fn){frame=fn;}};
const texture=new THREE.VideoTexture(video);
let renders=0,dpr=1;
const s=new Subject();
Object.assign(s,{ready:true,sharedVideo:texture,videoVersion:-1,sourceWidth:0,sourceHeight:0,targetWidth:0,targetHeight:0,size:new THREE.Vector2(),camera:new THREE.OrthographicCamera(),plane:new THREE.Mesh(new THREE.PlaneGeometry(),new THREE.MeshBasicMaterial()),target:{setSize(){}},renderer:{getSize:v=>v.set(640,360),getPixelRatio:()=>dpr,setSize(){},setRenderTarget(){},clear(){},render(){renders++;}}});
const bubbles=[{active:true}];
const draw=(w=640,h=360)=>s.draw(bubbles,w,h,video);
draw();assert.equal(renders,1);
for(let n=0;n<60;n++){video.currentTime+=.001;draw();}
assert.equal(renders,1,'clock movement without a new video frame does not redraw');
frame();draw();draw();assert.equal(renders,2);
video.videoWidth=1920;video.videoHeight=1080;draw();draw();assert.equal(renders,3);
dpr=1.5;draw();draw();assert.equal(renders,4);
draw(360,640);draw(360,640);assert.equal(renders,5);
bubbles[0].active=false;frame();draw(360,640);assert.equal(renders,5);
bubbles[0].active=true;draw(360,640);assert.equal(renders,6,'resuming bubbles uses the latest frame');
video.readyState=1;frame();draw(360,640);assert.equal(renders,6);
video.readyState=2;draw(360,640);assert.equal(renders,7);
s.videoTexture=undefined;draw(360,640);assert.equal(renders,8,'binding a texture invalidates the target');
console.log('PASS bubble background follows video frames and invalidates on source, viewport and DPR changes');
